const INTENT_MAPS = Object.fromEntries(
  Object.entries(INTENTS).map(([locale, values]) => {
    if (values.length !== PORTUGUESE_INTENTS.length) {
      throw new Error('Intent translation count mismatch for ' + locale);
    }
    return [locale, Object.fromEntries(PORTUGUESE_INTENTS.map((source, index) => [source, values[index]]))];
  }),
);

export function localeFromPath(relativePath) {
  const first = relativePath.split('/').filter(Boolean)[0];
  return LOCALES.includes(first) ? first : 'pt';
}

export function transformLocalizedHtml(html, locale) {
  if (!LOCALES.includes(locale)) throw new Error('Unsupported Aureum locale: ' + locale);
  let output = html;

  for (const [source, replacement] of COPY[locale]) {
    output = output.split(source).join(replacement);
  }

  if (locale !== 'pt') {
    const intents = INTENT_MAPS[locale];
    output = output.replace(/\bdata-intent=(["'])(.*?)\1/g, (match, quote, value) => {
      const translated = intents[value];
      return translated ? 'data-intent=' + quote + translated + quote : match;
    });
    const subjects = SUBJECTS[locale];
    output = output.replace(/\bdata-subject=(["'])(.*?)\1/g, (match, quote, value) => {
      const translated = subjects[value];
      return translated ? 'data-subject=' + quote + translated + quote : match;
    });
  }

  return output;
}

