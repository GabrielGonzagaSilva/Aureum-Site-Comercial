'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const asset=path.join(__dirname,'aureum-hero-user-print.svg');
const destination=path.join(__dirname,'public/assets/brand/aureum-hero-user-print.svg');
const homepage=path.join(__dirname,'public/index.html');
const heroCss=path.join(__dirname,'public/assets/css/aureum-logo-centered-preview.css');
const assert=(yes,label)=>{if(!yes) throw Error('AUREUM HERO LOGO QA: '+label);};
const source=fs.readFileSync(asset);
const hash=crypto.createHash('sha256').update(source).digest('hex');
assert(hash==='2341d484a5b86925632efe882354f5ca19506d0cc5fd0da4f54d4190bbf5bf96','Uploaded SVG hash mismatch');
assert(source.toString('utf8').includes('viewBox="0 0 785.539 538.869"'),'SVG dimensions mismatch');
assert(source.toString('utf8').includes('assessoria internacional'),'Original tagline missing');
const oldImage='<img class="hero-brand-center" src="/assets/brand/aureum-logo-white.svg" alt="Aureum" width="592" height="140" decoding="async" fetchpriority="high">';
const newImage='<img class="hero-brand-center" src="/assets/brand/aureum-hero-user-print.svg" alt="Aureum — assessoria internacional" width="786" height="539" decoding="async" fetchpriority="high">';
let html=fs.readFileSync(homepage,'utf8');
const pos=html.indexOf('class="hero hero-logo-centered-test"');
assert(pos>=0,'Approved centered hero missing');
const end=html.indexOf('</section>',pos);
assert(end>pos,'Hero bounds missing');
const hero=html.slice(pos,end);
assert(hero.split(oldImage).length===2,'Expected old centered image exactly once');
html=html.replace(oldImage,newImage);
assert(html.includes('Cidadania e vistos'),'Approved title was modified');
assert(html.includes('hero-tower-bridge.mp4'),'Approved background video missing');
assert(html.includes('class="hero-scroll-hint"'),'Scroll hint missing');
assert(html.includes('id="contato"'),'Contact section missing');
assert(html.includes('/assets/brand/aureum-logo-ink.svg'),'Header logo missing');
assert(html.includes('/assets/brand/aureum-logo-white.svg'),'Other existing logos modified');
fs.mkdirSync(path.dirname(destination),{recursive:true});
fs.writeFileSync(destination,source);
fs.writeFileSync(homepage,html,'utf8');
fs.appendFileSync(heroCss,"\n/* Portrait lockup: keep the uploaded image's intrinsic aspect ratio. */\n#home .hero-logo-centered-test .hero-brand-center {\n  width:clamp(285px,30vw,395px);\n  max-width:79%;\n  height:auto;\n  margin-bottom:clamp(21px,3vh,29px);\n  object-fit:contain;\n}\n@media(max-width:767px) {\n  #home .hero-logo-centered-test .hero-brand-center {\n    width:min(70vw,280px);\n    max-width:78%;\n    margin-bottom:23px;\n  }\n}\n@media(max-width:380px) {\n  #home .hero-logo-centered-test .hero-brand-center {width:min(70vw,250px);}\n}\n",'utf8');
assert(crypto.createHash('sha256').update(fs.readFileSync(destination)).digest('hex')===hash,'Emitted SVG hash mismatch');
console.log('AUREUM UPLOADED LOGO QA PASS: exact original SVG, center hero only, responsive portrait logo, original video, CTA, scroll, 9 destinations, brand assets and integrations preserved.');
